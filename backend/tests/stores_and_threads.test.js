process.env.JWT_SECRET = 'stores-threads-test-secret-with-sufficient-length'
const request = require('supertest')
const mongoose = require('mongoose')
const { MongoMemoryServer } = require('mongodb-memory-server')
const app = require('../server')
const fixtures = require('./helpers/tradeFixtures')
const Store = require('../models/Store')
const MessageThread = require('../models/MessageThread')
let mongo, f
beforeAll(async () => { mongo = await MongoMemoryServer.create({ instance: { storageEngine: 'wiredTiger' } }); await mongoose.connect(mongo.getUri()); f = await fixtures() })
afterAll(async () => { await mongoose.disconnect(); if (mongo) await mongo.stop() })
const auth = who => ({ Authorization: 'Bearer ' + f.tokens[who] })
test('new stores await review and only approved active stores are public', async () => {
  const created = await request(app).post('/api/stores').set(auth('supplier')).send({ name: 'متجر جديد', description: 'وصف المتجر', city: 'الرباط' })
  expect(created.status).toBe(201)
  expect(created.body.store.reviewStatus).toBe('pending')
  expect(created.body.store.isActive).toBe(false)
  expect((await request(app).get('/api/stores/' + created.body.store._id)).status).toBe(404)
  const list = await request(app).get('/api/stores')
  expect(list.body.data.some(s => s._id === String(f.store._id))).toBe(true)
  expect(list.body.data.some(s => s._id === created.body.store._id)).toBe(false)
})
test('store details contain only products associated with that store', async () => {
  const result = await request(app).get('/api/stores/' + f.store._id)
  expect(result.status).toBe(200)
  expect(result.body.products).toHaveLength(1)
  expect(result.body.products[0]._id).toBe(String(f.product._id))
})
test('RFQ creation initializes a buyer-owned thread and a persistent supplier offer', async () => {
  const created = await request(app).post('/api/rfq').set(auth('buyer')).send({ productId: f.product._id, buyerPhone: '+212600001122', quantity: 30 })
  expect(created.status).toBe(201)
  const id = created.body.rfq._id
  const thread = await MessageThread.findOne({ rfqId: id })
  expect(String(thread.buyerId)).toBe(String(f.buyer._id))
  const reply = await request(app).put('/api/rfq/' + id + '/respond').set(auth('supplier')).send({ unitPrice: 110, deliveryDays: 4 })
  expect(reply.status).toBe(200)
  const message = await request(app).post('/api/rfq/' + id + '/messages').set(auth('staff')).send({ content: 'الكمية جاهزة', senderRole: 'admin' })
  expect(message.status).toBe(201)
  expect(message.body.thread.messages.at(-1).senderRole).toBe('supplier')
  expect(message.body.thread.messages.at(-1).senderId).toBe(String(f.staff._id))
  const history = await request(app).get('/api/rfq/' + id + '/thread').set(auth('buyer'))
  expect(history.body.offers).toHaveLength(1)
  expect(history.body.offers[0].unitPrice).toBe(110)
})
test('RFQ cannot be created against a suspended store', async () => {
  await Store.updateOne({ _id: f.store._id }, { $set: { isActive: false } })
  const created = await request(app).post('/api/rfq').set(auth('buyer')).send({ productId: f.product._id, buyerPhone: '+212600001122', quantity: 30 })
  expect(created.status).toBe(404)
})
