test('manual recovery is single-operation scoped and concurrent callers cannot duplicate or replace a newer dossier',async()=>{
 const {owner,store}=await fixture(),staff=await account('staff'),buyer=await account('buyer')
 const fault=jest.spyOn(Audit,'updateOne').mockRejectedValueOnce(Error('synthetic outage'));expect((await submit(owner)).status).toBe(503);fault.mockRestore()
 const id=String((await state(owner)).verificationOperation.id)
 const path='/api/suppliers/me/verification-recover',adminPath='/api/admin/suppliers/'+owner._id+'/verification-recover'
 const send=(who=owner,p=path,body={operationId:id})=>request(app).post(p).set(auth(who)).send(body)
 for(const body of [{},{operationId:'bad'},{operationId:id,action:'approve'},{operationId:id,verificationRevision:999},{operationId:id,actorId:String(admin._id)}])expect((await send(owner,path,body)).status).toBe(400)
 expect((await send(staff)).status).toBe(403);expect((await send(buyer)).status).toBe(403)
 expect((await request(app).post(path).send({operationId:id})).status).toBe(401)
 expect((await state(owner)).verificationStatus).toBe('unverified');expect(await events(owner)).toHaveLength(0)
 const replies=await Promise.all([send(),send(),send(admin,adminPath),send(otherAdmin,adminPath)])
 expect(replies.map(r=>r.status)).toEqual([200,200,200,200])
 expect(replies.every(r=>r.body.operation.id===id&&r.body.operation.phase==='completed')).toBe(true)
 await proof(owner,store,'pending',1)
 expect((await decide(owner)).status).toBe(200);expect((await submit(owner,1,'001234567890004')).status).toBe(200)
 expect((await send()).status).toBe(409);expect((await send(admin,adminPath)).status).toBe(409)
 await proof(owner,store,'pending',3)
})
